"""Deterministic synthetic evaluation corpus (task brief S17.1).

The corpus is generated by code, never committed as binaries (S2 rule 4). Every entry carries the
text an ingestion pipeline would extract, so routing and retrieval metrics can run fully offline on
a host without PostgreSQL, Qdrant, an LLM key or a live Telegram token.

Coverage required by S17.1 and asserted in ``tests/evaluation/test_evaluation_harness.py``:
at least 10 PDF, 5 DOCX, 5 XLSX, 10 product images, 5 scanned documents, 5 contracts/invoices,
several documents about the same product, duplicated and contradictory data, unrelated documents,
and Azerbaijani / Russian / English content, in the hardware domain (printers, cameras, cables,
adapters).
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass

PDF = "application/pdf"
DOCX = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
XLSX = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
TXT = "text/plain"
PNG = "image/png"


@dataclass(frozen=True, slots=True)
class CorpusDocument:
    """One addressable document in the reference corpus."""

    document_id: str
    filename: str
    media_type: str
    language: str
    text: str
    metadata: Mapping[str, str]

    def matches(self, *terms: str) -> bool:
        """True when every term appears in the document text (case-insensitive)."""

        lowered = self.text.casefold()
        return all(term.casefold() in lowered for term in terms)


@dataclass(frozen=True, slots=True)
class CorpusImage:
    """One product image with the text a correct OCR pass must read off it.

    The harness stores OCR ground truth rather than pixels: no vision provider or model weights are
    available offline. Real image bytes are produced by the Phase 2/4 ingestion path, and the
    per-language OCR accuracy reported in ``docs/evaluation/BENCHMARK_RESULTS.md`` compares against
    ``ocr_ground_truth``.
    """

    image_id: str
    filename: str
    product_hint: str
    ocr_ground_truth: str
    language: str


@dataclass(frozen=True, slots=True)
class EvaluationCorpus:
    """The full reference corpus plus S17.1 coverage accounting."""

    documents: tuple[CorpusDocument, ...]
    images: tuple[CorpusImage, ...]

    def by_id(self, document_id: str) -> CorpusDocument:
        for document in self.documents:
            if document.document_id == document_id:
                return document
        raise KeyError(document_id)

    def with_metadata(self, key: str, value: str) -> tuple[CorpusDocument, ...]:
        return tuple(item for item in self.documents if item.metadata.get(key) == value)

    def coverage(self) -> Mapping[str, int]:
        """Count every S17.1 category; PDF count excludes nothing, categories may overlap."""

        media_counts: dict[str, int] = {}
        for document in self.documents:
            media_counts[document.media_type] = media_counts.get(document.media_type, 0) + 1
        return {
            "pdf": media_counts.get(PDF, 0),
            "docx": media_counts.get(DOCX, 0),
            "xlsx": media_counts.get(XLSX, 0),
            "txt": media_counts.get(TXT, 0),
            "images": len(self.images),
            "scanned_documents": len(self.with_metadata("scanned", "true")),
            "contracts_and_invoices": len(
                tuple(
                    item
                    for item in self.documents
                    if item.metadata.get("doc_kind") in {"contract", "invoice"}
                )
            ),
            "languages": len({item.language for item in self.documents}),
            "duplicate_groups": len(
                {
                    item.metadata["duplicate_group"]
                    for item in self.documents
                    if "duplicate_group" in item.metadata
                }
            ),
            "contradiction_groups": len(
                {
                    item.metadata["contradiction_group"]
                    for item in self.documents
                    if "contradiction_group" in item.metadata
                }
            ),
            "unrelated_documents": len(self.with_metadata("doc_kind", "unrelated")),
            "injection_documents": len(self.with_metadata("doc_kind", "injection")),
        }


def _doc(
    document_id: str,
    filename: str,
    media_type: str,
    language: str,
    text: str,
    **metadata: str,
) -> CorpusDocument:
    return CorpusDocument(
        document_id=document_id,
        filename=filename,
        media_type=media_type,
        language=language,
        text=text,
        metadata=dict(metadata),
    )


