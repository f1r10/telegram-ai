def build_reference_corpus() -> EvaluationCorpus:
    """Return the deterministic reference corpus.

    Documents are de-duplicated by ``document_id`` so ``by_id`` stays unambiguous. Near-duplicate
    *content* is kept on purpose (see the ``duplicate_group`` metadata) because S17.1 requires the
    corpus to contain duplicated data.
    """

    unique: dict[str, CorpusDocument] = {}
    for document in _DOCUMENTS:
        unique.setdefault(document.document_id, document)
    return EvaluationCorpus(documents=tuple(unique.values()), images=_IMAGES)
