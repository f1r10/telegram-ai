def test_generated_fixtures_are_real_and_well_formed(tmp_path: Path) -> None:
    fixtures = generate_fixtures(tmp_path)
    assert set(fixtures) == {"simple.pdf", "headings.docx", "multi_sheet.xlsx", "sample.png"}
    assert is_well_formed_pdf(fixtures["simple.pdf"].read_bytes())
    assert is_well_formed_ooxml(fixtures["headings.docx"].read_bytes())
    assert is_well_formed_ooxml(fixtures["multi_sheet.xlsx"].read_bytes())
    assert is_well_formed_png(fixtures["sample.png"].read_bytes())


def test_pdf_fixture_bytes_are_deterministic(tmp_path: Path) -> None:
    first = generate_fixtures(tmp_path / "first")["simple.pdf"].read_bytes()
    second = generate_fixtures(tmp_path / "second")["simple.pdf"].read_bytes()
    assert first == second


def test_no_binary_fixture_is_committed_to_the_repository() -> None:
    """The generated bytes must never be tracked: the tree must hold no fixture binaries at all."""

    offenders: list[str] = []
    for name in _SCANNED_DIRECTORIES:
        base = _REPO_ROOT / name
        if base.is_dir():
            offenders += [
                path.relative_to(_REPO_ROOT).as_posix()
                for path in base.rglob("*")
                if path.is_file() and path.suffix.casefold() in _BINARY_SUFFIXES
            ]
    offenders += [
        path.name for path in _REPO_ROOT.glob("*.*") if path.suffix.casefold() in _BINARY_SUFFIXES
    ]
    assert offenders == [], offenders


