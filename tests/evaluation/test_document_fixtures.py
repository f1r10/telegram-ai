def _run_main(monkeypatch: pytest.MonkeyPatch, tmp_path: Path, *, evaluate: bool) -> None:
    pdf = generate_fixtures(tmp_path)["simple.pdf"]
    truth = tmp_path / "truth.json"
    truth.write_text(json.dumps(["PRIVATE-LABEL-XYZ"]), encoding="utf-8")
    models = tmp_path / "models"
    models.mkdir(exist_ok=True)
    argv = [
        "evaluate_docling",
        "--pdf",
        str(pdf),
        "--truth",
        str(truth),
        "--local-models",
        str(models),
    ]
    if evaluate:
        argv.append("--evaluate")
    monkeypatch.setattr(sys, "argv", argv)


def test_dry_run_reports_a_hash_and_never_the_private_labels(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    _run_main(monkeypatch, tmp_path, evaluate=False)
    evaluate_docling.main()
    captured = capsys.readouterr().out
    payload = json.loads(captured)
    assert payload["status"] == "DRY_RUN"
    assert payload["samples"] == 1
    assert len(payload["truth_sha256"]) == 64
    assert "PRIVATE-LABEL-XYZ" not in captured


def test_unavailable_status_is_preserved_when_no_engine_is_installed(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    if importlib.util.find_spec("docling") is not None:
        pytest.skip("docling installed; the unavailable path cannot be exercised")
    _run_main(monkeypatch, tmp_path, evaluate=True)
    with pytest.raises(SystemExit) as exit_info:
        evaluate_docling.main()
    assert exit_info.value.code == 2
    captured = capsys.readouterr().out
    assert json.loads(captured) == {"status": "UNAVAILABLE", "content_disclosed": False}
    assert "PRIVATE-LABEL-XYZ" not in captured
