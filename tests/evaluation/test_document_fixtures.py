def test_native_parser_recovers_generated_pdf_text(tmp_path: Path) -> None:
    """A real offline measurement: the shipped parser reads the fixture it was generated from."""

    pdf = generate_fixtures(tmp_path)["simple.pdf"]
    baseline = PdfParser().parse(pdf, source_file_id=0, media_type="application/pdf")
    labels = ["PRN-M404", "Gigabit Ethernet RJ45", "Duplex printing"]
    recall = score_phrases(baseline.text(), baseline.text(), labels)
    assert recall.samples == 3
    assert recall.native_hits == 3, baseline.text()
    assert all(normalize(item) in normalize(baseline.text()) for item in labels)


